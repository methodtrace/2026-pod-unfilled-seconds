"""Consistency checks before any experiment (podsim/checks.py): the structural floor against the undershoot
engines, pod construction against brute force, the stability criterion and the non-CM tau bound. Writes
checks_report.md and checks.json (keys item1, item2, item7, item8). Exit 1 on any failure."""
import json
import os
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

from podsim import structural, checks  # noqa: E402
from podsim import engines as E  # noqa: E402
from podsim import registry as REG  # noqa: E402


def ms(m):
    return "{" + ", ".join(str(a) for a in m) + "}"


def main():
    L = []
    w = L.append
    out = {}
    T_ = {}
    w("# Checks report")
    w("")
    w("Generated by `python3 run_checks.py`. Exact undershoot engines imported in place from %s (the undershoot companion's development engines, hash-pinned; "
      "its public release, cited in vendor/sumset-undershoot/CITATION.cff, restructures them); sha256 verified against ENGINES.sha256 at import:" % "vendor/sumset-undershoot")
    w("")
    for p, h in sorted(E.HASHES.items()):
        w("- `%s` %s" % (p, h))
    w("")

    t = time.time()
    r1 = structural.crosscheck()
    out["item1"] = r1
    w("## Check 1: structural floor, direct DP against the undershoot engines (checks.json key item1)")
    w("")
    w("Menus: the seven study menus plus every 2- and 3-subset of {5, 6, 10, 15, 20, 30, 45, 60} and "
      "{10, 15, 20, 30} (%d distinct menus). Caps h = 1 to 12, targets T = 0 to 300 s." % r1["menus"])
    w("")
    w("- Direct DP (least number of parts, `structural.undershoot_table`) against E-A (iterated shifted-OR "
      "sumsets on raw seconds, `undershoot_scan`): %d comparisons, 0 mismatches." % r1["E-A comparisons"])
    w("- Against E-B (Apery formula on the gcd-reduced set, D = (T mod g) + g D(T div g)), every fifth menu: "
      "%d comparisons, 0 mismatches." % r1["E-B comparisons"])
    w("- Any mismatch raises AssertionError.")
    T_["item1"] = time.time() - t
    w("")

    t = time.time()
    r2 = checks.pod_check(n_cases=(300 if REG.tier_name() == "quick" else 3000))
    out["item2"] = r2
    w("## Check 2: pod construction against brute force (checks.json key item2)")
    w("")
    w("Random pools of 0 to 8 distinct creatives, durations from seven menus (including the odd menu "
      "{7, 9, 11}), integer per-second values 1 to 60 (so ties are frequent), T in 0..200 s, cap in "
      "{none, 1, 2, 3, 4, 6}; seed %d." % r2["seed"])
    w("")
    w("- `select_menu` (count-vector enumeration, the production method) = `dp_select` (exact DP over "
      "(seconds used, ads used) on distinct creatives, the reference method) = `pod_oracle` (all subsets), "
      "for both policies, on (seconds, revenue) of the seconds-max pod and (revenue, seconds) of the "
      "revenue-max pod: %d cases, 0 mismatches. Also checked: cap respected, no creative reused." % r2["menu_cases"])
    w("- Arithmetic relaxation (elastic creatives, any integer duration in [m, M]): `select_elastic` = "
      "`dp_select(elastic)` = `elastic_oracle` (every subset and every duration assignment): %d cases, "
      "0 mismatches." % r2["elastic_cases"])
    T_["item2"] = time.time() - t
    w("")
    w("The knapsack companion's necessary conditions on simulated (full break, remainder) hull pairs are "
      "checked by X5 (x5/hullchecks.json).")
    w("")

    t = time.time()
    ex = checks.stability_examples()
    r7 = checks.stability_check()
    out["item7"] = r7
    out["item7_examples"] = ex
    w("## Check 3: stability criterion, Proposition 2 (checks.json key item7)")
    w("")
    w("Example 3 reproduced exactly (undershoot by h = 1, 2, ...):")
    w("")
    for k, v in ex.items():
        w("- %s: %s" % (k, v))
    w("")
    w("Grid: base menus A = every 2- and 3-subset of {5, 6, 10, 15, 20, 30, 45, 60} (84), added duration c = "
      "every grid value not in A, window T = 60..240 s (integers). Membership in <A> and <A u {c}> and the "
      "predecessor p_A(T) come from engine E-C gap sets (independent of the DP).")
    w("")
    w("- Pointwise identity D_h(A;T) >= T - p_A(T), with equality iff h >= l_A(p_A(T)), for h = 1..40: "
      "%d checks, 0 failures." % r7["pointwise_identity_checks"])
    w("- Stable cap h_stab = max over the window of l(p(T)) for both A and A u {c} (largest seen: %d). At "
      "h_stab, h_stab + 1, h_stab + 2 (%d (A, c, h) cases): the window total drops on adding c if and only if "
      "some T in the window has a new semigroup element in (p_A(T), T]; also checked pointwise per T (drop at T "
      "iff such an element exists). 0 failures, both directions." % (r7["h_stab_max"], r7["caps_checked"]))
    w("- At h_stab, over %d (A, c) pairs: adding c helps on %d, does not help on %d. Pointwise over (A, c, T): "
      "helps %d, does not %d." % (r7["pairs"], r7["window_helps"], r7["window_no_help"], r7["pointwise_helps"],
                                  r7["pointwise_no_help"]))
    w("- Of the %d helping pairs, %d help at least one target T that stays outside <A u {c}> (gain by a new "
      "predecessor, not a filled target: the case a criterion on filled targets alone would miss)." % (r7["window_helps"],
                                                                                    r7["helps_target_stays_gap"]))
    T_["item7"] = time.time() - t
    w("")
    w("Note: the stable cap here is per-window and can be large (up to %d for the 2- and 3-part grid menus on "
      "[60, 240]), well above the caps of the X1 grid; at caps below h_stab the criterion does not apply and "
      "is not claimed." % r7["h_stab_max"])
    w("")

    t = time.time()
    rows = checks.tau_check()
    nc = [r for r in rows if not r["cm"]]
    out["item8"] = [{k: (list(v) if isinstance(v, tuple) else v) for k, v in r.items()} for r in rows]
    w("## Check 4: non-CM tau and the non-CM bound of the regularity companion (checks.json key item8)")
    w("")
    w("Every 3-part menu from {5, 6, 10, 15, 20, 30, 45, 60} (56 menus), gcd-reduced to A0 = {0, a, b, d}. "
      "hA0 by E-A sumsets compared with I_h = {x in [0, hd]: x in <A>, hd - x in <d - A>} (E-C gap sets) for "
      "h = 1..3d + 10; tau = 1 + the last failing h. CM status from this comparison agrees with E-B's Apery "
      "test on all 56. Conductors c1, c2 by E-C Frobenius numbers.")
    w("")
    w("Result: **%d of %d non-CM** (expected 9). The bound (tau - 1) d >= c1 + c2 + d, holds for all; "
      "equality exactly on the sets of the form {0, b - 1, b + 1, 2b} with b even." % (len(nc), len(rows)))
    w("")
    w("| Menu (s) | A0 | failing h | tau | c1 | c2 | (tau - 1) d | c1 + c2 + d | equality | family | bound on tau | fan reg(I) |")
    w("| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |")
    for r in nc:
        w("| %s | %s | %s | %d | %d | %d | %d | %d | %s | %s | %.2f | %s |" % (
            ms(r["menu"]), ms(r["A0"]), ",".join(map(str, r["failing"])), r["tau"], r["c1"], r["c2"], r["lhs"],
            r["rhs"], "yes" if r["equality"] else "no", "yes" if r["family"] else "no", r["bound_tau"],
            r["fan_reg"]))
    w("")
    w("fan reg(I) is the undershoot engines' fan.py Castelnuovo-Mumford regularity of the toric ideal (BGM Thm 2.8), shown "
      "for reference only: in every row it equals tau + 1, which is consistent with tau being the sumset "
      "regularity index; not used further.")
    w("")
    w("Bound tight (equality) for {5, 15, 20} and {15, 45, 60}, both reducing to {0, 1, 3, 4} = "
      "{0, b - 1, b + 1, 2b} with b = 2. Loosest relative case: {5, 45, 60}, bound 3.67 against tau "
      "8.")
    T_["item8"] = time.time() - t
    fan_ok = all(r["fan_reg"] == r["tau"] + 1 for r in nc)
    if not fan_ok:
        L[-1] += " (fan reg(I) differs from tau + 1 for some row; see table.)"
    ok = len(nc) == 9
    d = REG.out_dir("checks")
    REG.write_json(os.path.join(d, "checks.json"), out)
    REG.write_text(os.path.join(d, "checks_report.md"), "\n".join(L) + "\n")
    for k, v in T_.items():
        REG.write_timing(d, k, v)
    print("checks", "PASS" if ok else "FAIL", "non-CM", len(nc), "fan reg = tau+1:", fan_ok)
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
