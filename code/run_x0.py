"""X0: check the simulator against two tables of fixed reference values (podsim/x0.py), regression checks computed
independently of the dynamic program; write x0_report.md. Exit status 1 on any mismatch."""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

from podsim import x0, structural  # noqa: E402
from podsim import engines as E  # noqa: E402
from podsim import registry as REG  # noqa: E402
from podsim.numeric import xsum  # noqa: E402


def menu_s(m):
    return "{" + ", ".join(str(a) for a in m) + "}"


def main():
    p1 = x0.reference_check_1()
    p2 = x0.reference_check_2()
    alt = x0.reference2_alternatives()
    ok = all(c["match"] for _, cells in p1 for c in cells) and all(r["match"] for r in p2)
    L = []
    w = L.append
    w("# X0: regression checks against fixed reference values")
    w("")
    w("Generated by `python3 run_x0.py`. Reference values: two fixed tables hard-coded in `podsim/x0.py`, computed "
      "independently of the dynamic program; every cell is recomputed here and must match.")
    w("Exact undershoot engines: vendor/sumset-undershoot (the undershoot companion's development engines, hash-pinned; its public release, cited in vendor/sumset-undershoot/CITATION.cff, restructures them); sha256 of each "
      "imported file:")
    w("")
    for p, h in sorted(E.HASHES.items()):
        w("- `%s` %s" % (p, h))
    w("")
    w("Overall status: **%s**." % ("ALL CELLS MATCH" if ok else "MISMATCH, see below"))
    w("")
    w("## Reference check 1: mean unfilled seconds per break, unlimited demand, rho = 1")
    w("")
    w("Breaks B uniform on {60, 90, 120, 150, 180} s. Remainder: S uniform on {5, 10, 15, 20, 45} s, always present, "
      "T = B - S (25 equally likely targets). Value = exact mean of D_h(A;T) over the uniform grid, by Fraction. "
      "Cap convention (a): maxseq = h applies to the dynamic remainder alone. Every cell computed twice "
      "(direct DP in podsim/structural.py and engine E-A on raw seconds); the two agree exactly.")
    w("")
    w("### Our table (convention a), exact fractions in parentheses")
    w("")
    w("| Menu | h = 4, grid | h = 4, remainder | h = 6, grid | h = 6, remainder | h = 8, remainder |")
    w("| --- | --- | --- | --- | --- | --- |")
    for menu, cells in p1:
        w("| %s | %s |" % (menu_s(menu), " | ".join("%s (%s)" % (c["ours"], c["exact"]) for c in cells)))
    w("")
    w("### Reference values")
    w("")
    w("| Menu | h = 4, grid | h = 4, remainder | h = 6, grid | h = 6, remainder | h = 8, remainder |")
    w("| --- | --- | --- | --- | --- | --- |")
    for menu, cells in p1:
        w("| %s | %s |" % (menu_s(menu), " | ".join(c["reference"] for c in cells)))
    w("")
    w("### Cell by cell")
    w("")
    w("| Menu | h = 4, grid | h = 4, remainder | h = 6, grid | h = 6, remainder | h = 8, remainder |")
    w("| --- | --- | --- | --- | --- | --- |")
    for menu, cells in p1:
        w("| %s | %s |" % (menu_s(menu), " | ".join("MATCH" if c["match"] else "MISMATCH (%s vs %s)" % (c["ours"], c["reference"]) for c in cells)))
    w("")
    nexact = xsum(1 for _, cells in p1 for c in cells if c["exact_2dp"])
    w("Every exact mean is a multiple of 1/25 s, so all %d of 20 cells are exactly representable at two decimals: "
      "the match is exact, not a rounding coincidence." % nexact)
    w("")
    w("### For reference: convention (b), remainder cap h - 1 (knapsack companion: the structured spot counts toward K = h)")
    w("")
    w("| Menu | h = 4, remainder | h = 6, remainder | h = 8, remainder |")
    w("| --- | --- | --- | --- |")
    for menu, cells in p1:
        w("| %s | %s |" % (menu_s(menu), " | ".join(c["conv_b"] for c in cells if c["kind"] == "remainder")))
    w("")
    w("The reference remainder columns are reproduced by convention (a) and not by (b); for example {15, 30} at h = 4 "
      "gives 14.00 s under (a) and 27.20 s under (b). So the reference values follow convention (a), the OpenRTB "
      "signaling convention.")
    w("")
    w("## Reference check 2: least maxseq for exact fill of every break in [60, 180] s on the menu's lattice")
    w("")
    w("Lattice = multiples of the menu gcd g. Least h with D_h(A;T) = 0 for every such T. Computed by the direct DP, "
      "by engine E-A, and by the closed form h* = ceil((floor(U/g) + c2)/d) of Proposition 1(c) "
      "(c2 = conductor of the reflected semigroup <d - A> after gcd reduction, from engine E-C). Column Reference: "
      "the fixed reference value; column Appendix h*: the least cap on [60, 180] stated in the paper's "
      "Appendix A of the paper.")
    w("")
    w("| Menu | g | A0 (reduced) | CM | c1 | c2 | Direct DP | E-A | Closed form | Reference | Appendix h* | Status |")
    w("| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |")
    for r in p2:
        cf = r["cf"]
        w("| %s | %d | %s | %s | %d | %d | %d | %d | %d | %d | %d | %s |" % (
            menu_s(r["menu"]), cf["g"], menu_s(cf["A0"]), "yes" if cf["cm"] else "no", cf["c1"], cf["c2"],
            r["direct"], r["engine_a"], r["closed"], r["reference"], r["companion"], "MATCH" if r["match"] else "MISMATCH"))
    w("")
    pre = all(r["cf"]["applies"] and r["cf"]["least_by_b"] for r in p2)
    if not pre:
        ok = False
    w("Preconditions of Proposition 1(c) checked in code for every menu (CM, L = 60 >= g c1, and "
      "floor(U/g) - floor(L/g) >= d - 1 for part (b)): %s. So the closed form is certified least, and "
      "the three computations agree. The form ceil((U/g + F + 1)/d), F the Frobenius "
      "number of the reflected menu, is the same formula (c2 = F + 1)." % ("all hold" if pre else "SOME FAIL"))
    w("")
    w("For comparison, other readings of 'lattice' (not used; they do not change the result where defined):")
    w("")
    w("| Menu | integers, fill up to T mod g | 5 s lattice | 15 s lattice |")
    w("| --- | --- | --- | --- |")
    for menu, r in alt.items():
        w("| %s | %s | %s | %s |" % (menu_s(menu), r["integers, up to T mod g"], r["5 s lattice"], r["15 s lattice"]))
    w("")
    w("The integer reading equals the gcd-lattice reading for every menu (the reduction D = (T mod g) + g D(T div g)). "
      "On the 5 s lattice the menus with gcd 15 or 3 ({15, 30}, {15, 30, 60}, {6, 15, 30}) can never fill "
      "every target, and the 15 s lattice gives smaller caps for the gcd-5 menus; neither matches the reference "
      "column, so the reference values use the gcd lattice.")
    REG.write_text(os.path.join(REG.out_dir("x0"), "x0_report.md"), "\n".join(L) + "\n")
    print("X0", "PASS" if ok else "FAIL")
    for menu, cells in p1:
        print(menu, [c["ours"] for c in cells], [c["match"] for c in cells])
    for r in p2:
        print(r["menu"], r["direct"], r["engine_a"], r["closed"], r["reference"], r["companion"], r["match"])
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
